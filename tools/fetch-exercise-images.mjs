/**
 * Downloads exercise photo pairs from free-exercise-db (public domain,
 * github.com/yuhonas/free-exercise-db) per the hand-curated mapping in
 * tools/exercise-image-map.json, then generates:
 *   - src/data/exerciseImages.ts      (static require() pairs)
 *   - src/data/exerciseDetails.gen.ts (instructions / secondary muscles / level)
 *   - assets/exercises/ATTRIBUTION.md
 *
 * Usage: node tools/fetch-exercise-images.mjs [--force]
 * The script hard-fails if any mapped id is missing from the dataset, so a
 * typo in the map can never ship a broken require().
 */
import { mkdir, readFile, writeFile, access } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MAP_PATH = path.join(ROOT, 'tools', 'exercise-image-map.json');
const ASSETS_DIR = path.join(ROOT, 'assets', 'exercises');
const IMAGES_TS = path.join(ROOT, 'src', 'data', 'exerciseImages.ts');
const DETAILS_TS = path.join(ROOT, 'src', 'data', 'exerciseDetails.gen.ts');

const DATASET_URL =
  'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/dist/exercises.json';
const IMAGE_BASE =
  'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/exercises/';

const FORCE = process.argv.includes('--force');
const SIZE_WARN_BYTES = 150 * 1024;

function titleCase(s) {
  return s.replace(/\b\w/g, (c) => c.toUpperCase());
}

async function exists(p) {
  try {
    await access(p);
    return true;
  } catch {
    return false;
  }
}

async function download(url, dest) {
  for (let attempt = 1; attempt <= 2; attempt++) {
    try {
      const res = await fetch(url);
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const buf = Buffer.from(await res.arrayBuffer());
      await writeFile(dest, buf);
      return buf.length;
    } catch (e) {
      if (attempt === 2) throw new Error(`${url}: ${e.message}`);
    }
  }
}

/** Run tasks with limited concurrency. */
async function pool(tasks, limit = 5) {
  const results = [];
  let i = 0;
  await Promise.all(
    Array.from({ length: limit }, async () => {
      while (i < tasks.length) {
        const idx = i++;
        results[idx] = await tasks[idx]();
      }
    }),
  );
  return results;
}

const map = JSON.parse(await readFile(MAP_PATH, 'utf8'));
const entries = Object.entries(map).filter(([, dbId]) => dbId !== null);

console.log(`Fetching dataset index…`);
const dataset = await (await fetch(DATASET_URL)).json();
const byId = new Map(dataset.map((e) => [e.id, e]));
console.log(`Dataset: ${dataset.length} exercises. Map: ${entries.length} mapped ids.`);

// --- Validate the whole map before touching anything -----------------------
const missing = entries.filter(([, dbId]) => !byId.has(dbId));
if (missing.length > 0) {
  console.error('\nMap ids NOT found in the dataset:');
  for (const [ourId, dbId] of missing) console.error(`  ${ourId} -> ${dbId}`);
  console.error('\nFix tools/exercise-image-map.json and re-run.');
  process.exit(1);
}

// --- Download image pairs ---------------------------------------------------
let totalBytes = 0;
const oversized = [];
const downloads = [];
for (const [ourId, dbId] of entries) {
  const record = byId.get(dbId);
  const images = record.images ?? [];
  if (images.length < 2) {
    console.error(`  ${ourId}: dataset record ${dbId} has ${images.length} images — need 2`);
    process.exit(1);
  }
  for (const frame of [0, 1]) {
    downloads.push(async () => {
      const dir = path.join(ASSETS_DIR, ourId);
      await mkdir(dir, { recursive: true });
      const dest = path.join(dir, `${frame}.jpg`);
      if (!FORCE && (await exists(dest))) return { skipped: true };
      const bytes = await download(IMAGE_BASE + images[frame], dest);
      totalBytes += bytes;
      if (bytes > SIZE_WARN_BYTES) oversized.push(`${ourId}/${frame}.jpg (${(bytes / 1024).toFixed(0)}KB)`);
      return { bytes };
    });
  }
}

console.log(`Downloading ${downloads.length} images…`);
const results = await pool(downloads, 5);
const skipped = results.filter((r) => r?.skipped).length;
console.log(
  `Done: ${results.length - skipped} downloaded (${(totalBytes / 1024 / 1024).toFixed(1)}MB), ${skipped} already present.`,
);
if (oversized.length > 0) {
  console.warn(`\n⚠ ${oversized.length} files exceed 150KB (consider a sharp downscale pass):`);
  oversized.forEach((f) => console.warn(`  ${f}`));
}

// --- Generate src/data/exerciseImages.ts ------------------------------------
const imagesTs = [
  '// AUTO-GENERATED by tools/fetch-exercise-images.mjs — do not edit.',
  '// Images: free-exercise-db (github.com/yuhonas/free-exercise-db), public domain (Unlicense).',
  "import { ImageSourcePropType } from 'react-native';",
  '',
  'export const exerciseImages: Record<string, [ImageSourcePropType, ImageSourcePropType]> = {',
  ...entries.map(
    ([ourId]) =>
      `  '${ourId}': [require('../../assets/exercises/${ourId}/0.jpg'), require('../../assets/exercises/${ourId}/1.jpg')],`,
  ),
  '};',
  '',
  'export function getExerciseImages(',
  '  id: string,',
  '): [ImageSourcePropType, ImageSourcePropType] | undefined {',
  '  return exerciseImages[id];',
  '}',
  '',
].join('\n');
await writeFile(IMAGES_TS, imagesTs);
console.log(`Wrote ${path.relative(ROOT, IMAGES_TS)} (${entries.length} entries).`);

// --- Generate src/data/exerciseDetails.gen.ts --------------------------------
const detailEntries = entries.map(([ourId, dbId]) => {
  const r = byId.get(dbId);
  return {
    ourId,
    instructions: r.instructions ?? [],
    secondaryMuscles: (r.secondaryMuscles ?? []).map(titleCase),
    level: r.level,
  };
});
const detailsTs = [
  '// AUTO-GENERATED by tools/fetch-exercise-images.mjs — do not edit.',
  '// Source: free-exercise-db (github.com/yuhonas/free-exercise-db), public domain (Unlicense).',
  '',
  'export interface ExerciseDetails {',
  '  instructions: string[];',
  '  secondaryMuscles: string[];',
  '  level?: string;',
  '}',
  '',
  'export const exerciseDetails: Record<string, ExerciseDetails> = {',
  ...detailEntries.map(
    (d) =>
      `  '${d.ourId}': ${JSON.stringify({
        instructions: d.instructions,
        secondaryMuscles: d.secondaryMuscles,
        level: d.level,
      })},`,
  ),
  '};',
  '',
  'export function getExerciseDetails(id: string): ExerciseDetails | undefined {',
  '  return exerciseDetails[id];',
  '}',
  '',
].join('\n');
await writeFile(DETAILS_TS, detailsTs);
console.log(`Wrote ${path.relative(ROOT, DETAILS_TS)}.`);

// --- Attribution --------------------------------------------------------------
await mkdir(ASSETS_DIR, { recursive: true });
await writeFile(
  path.join(ASSETS_DIR, 'ATTRIBUTION.md'),
  [
    '# Exercise images',
    '',
    'Photos in this directory come from the free-exercise-db project',
    '(https://github.com/yuhonas/free-exercise-db), released into the public',
    'domain under the Unlicense. Downloaded and organized by',
    '`tools/fetch-exercise-images.mjs`; the mapping to GymSync exercise ids',
    'lives in `tools/exercise-image-map.json`.',
    '',
  ].join('\n'),
);
console.log('Wrote assets/exercises/ATTRIBUTION.md. All done.');
